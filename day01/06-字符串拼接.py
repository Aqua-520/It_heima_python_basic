# 两个字符串在赋值时会自动被拼接
str1 = '我是' '大帅比'
print(str1)

# 可以使用+号进行字符串的连接
str2 = '0基础' + '学it' + '月薪过万' + '就来黑马程序员'
print(str2)

# 两个字符串变量之间,只可以使用+号进行拼接
a = '我好想'
b = '变成美少女'
strPlus = a + b
print(strPlus)

# 拼接名言
life = '人生苦短'
use_python = '我用python'

name_result = '吉多范罗苏姆:' + life + ',' + use_python + '!'
print(name_result)